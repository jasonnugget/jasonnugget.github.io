document.querySelectorAll("[data-project-art]").forEach((element) => {
  // Remove background speckles and crop empty margins without shifting the art.
  const lines = (projectArt[element.dataset.projectArt] || "")
    .replace(/\./g, " ")
    .split("\n");
  while (lines.length && !lines[0].trim()) lines.shift();
  while (lines.length && !lines[lines.length - 1].trim()) lines.pop();
  if (!lines.length) return;

  const left = Math.min(...lines.filter((line) => line.trim()).map((line) => line.search(/\S/)));
  const right = Math.max(...lines.map((line) => line.trimEnd().length));
  element.textContent = lines.map((line) => line.slice(left, right).trimEnd()).join("\n");
  element.style.setProperty("--art-width", (right - left) * 0.6);
  element.style.setProperty("--art-rows", lines.length);
});

const links = document.querySelectorAll(".nav-link");
const tabs = document.querySelectorAll(".tab");

if (links.length && tabs.length) {
  // 404.html stashes the path it was reached by, since GitHub Pages has no
  // rewrites and serves 404 for /about, /projects, /contact.
  const stashed = sessionStorage.getItem("redirect");
  if (stashed) {
    sessionStorage.removeItem("redirect");
    history.replaceState(null, "", stashed);
  }

  const routes = ["about", "projects", "contact"];

  const currentTab = () => {
    const name = location.pathname.replace(/^\/+|\/+$/g, "");
    return routes.includes(name) ? name : "about";
  };

  const render = (target) => {
    links.forEach((l) => l.classList.toggle("active", l.dataset.tab === target));
    tabs.forEach((tab) => tab.classList.toggle("active", tab.id === target));
  };

  links.forEach((link) => {
    link.addEventListener("click", (e) => {
      if (e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return;
      e.preventDefault();
      history.pushState(null, "", link.getAttribute("href"));
      render(link.dataset.tab);
    });
  });

  window.addEventListener("popstate", () => render(currentTab()));

  render(currentTab());
}


const tocLinks = document.querySelectorAll(".toc nav a");
const sections = document.querySelectorAll(".post section[id]");

if (tocLinks.length && sections.length) {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          tocLinks.forEach((a) =>
            a.classList.toggle(
              "active",
              a.getAttribute("href") === "#" + entry.target.id
            )
          );
        }
      });
    },
    { rootMargin: "-20% 0px -70% 0px" }
  );

  sections.forEach((s) => observer.observe(s));
}
